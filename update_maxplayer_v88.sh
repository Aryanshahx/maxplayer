    this.sizeBytes,
    this.lastModifiedMs,
    this.width,
    this.height,
    this.httpHeaders,
  });""")

apply(
"""      lastModifiedMs: lastModifiedMs,
      width: width,
      height: height,
    );
  }
}""",
"""      lastModifiedMs: lastModifiedMs,
      width: width,
      height: height,
      httpHeaders: httpHeaders,
    );
  }
}""")

open(p, "w", encoding="utf-8").write(s)
print("  OK")
PYEOF

echo "==> Patching lib/state/media_player_state.dart (playCloudStream + pass through headers)"
python3 - <<'PYEOF'
import sys
p = "lib/state/media_player_state.dart"
s = open(p, encoding="utf-8").read()

def apply(old, new):
    global s
    if old not in s:
        sys.exit(f"[media_player_state.dart] anchor not found, aborting:\n{old[:150]}")
    s = s.replace(old, new, 1)

