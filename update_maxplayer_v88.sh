print("  OK")
PYEOF

echo "==> Patching lib/screens/library_screen.dart (wire authenticated playback for Cloud Storage)"
python3 - <<'PYEOF'
import sys
p = "lib/screens/library_screen.dart"
s = open(p, encoding="utf-8").read()

def apply(old, new):
    global s
    if old not in s:
        sys.exit(f"[library_screen.dart] anchor not found, aborting:\n{old[:150]}")
    s = s.replace(old, new, 1)

apply(
