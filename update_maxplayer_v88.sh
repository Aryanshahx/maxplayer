#!/usr/bin/env bash
# Max Player v88 update script
# Run from the repo root: ~/IdeaProjects/maxplayer
#
# Adds real "Sign in with Google" for Cloud Storage (Google Drive), so
# the app can see and stream your PRIVATE Drive files, not just publicly
# shared links. Written against your actual v87 code - no file was
# restructured, only added to.
set -euo pipefail

if [ ! -f "pubspec.yaml" ]; then
  echo "ERROR: run this from the maxplayer repo root (pubspec.yaml not found here)."
  exit 1
fi

echo "==> Patching pubspec.yaml (add google_sign_in dependency)"
python3 - <<'PYEOF'
import sys
p = "pubspec.yaml"
s = open(p, encoding="utf-8").read()
old = """  path: ^1.9.0
  intl: ^0.19.0

dev_dependencies:"""
new = """  path: ^1.9.0
  intl: ^0.19.0

  # v88: real "Sign in with Google" for private Drive file access (the
  # existing API-key mode can only see publicly-shared files). No client
  # secret ships in the app - Android matches the OAuth client by package
  # name + signing certificate SHA-1, registered once in Cloud Console.
  google_sign_in: ^6.2.1

dev_dependencies:"""
if old not in s:
    sys.exit("[pubspec.yaml] anchor not found, aborting")
s = s.replace(old, new, 1)
open(p, "w", encoding="utf-8").write(s)
print("  OK")
PYEOF

echo "==> Patching lib/models/video_track.dart (optional httpHeaders field)"
python3 - <<'PYEOF'
import sys
p = "lib/models/video_track.dart"
s = open(p, encoding="utf-8").read()

def apply(old, new):
    global s
    if old not in s:
        sys.exit(f"[video_track.dart] anchor not found, aborting:\n{old[:150]}")
    s = s.replace(old, new, 1)

apply(
